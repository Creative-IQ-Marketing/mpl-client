/** Generates Netlify routing, XML sitemaps, and robots.txt. */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  IMAGE_SITEMAP,
  SEO_PAGES,
  SITE_URL,
  toCanonical,
} from "./seo-catalog.mjs";
import {
  LEGACY_REDIRECTS,
  SPA_ROUTES,
} from "../src/data/siteConfig.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const publicDir = join(root, "public");
const today = new Date().toISOString().slice(0, 10);

// ─── _redirects ─────────────────────────────────────────────────────────────
const redirectLines = [
  "# Auto-generated by scripts/generate-seo-files.mjs — do not edit by hand.",
  "#",
  "# 1) Legacy / alias URLs → canonical paths (301)",
  "# 2) Trailing-slash → non-slash (301) so sitemap URLs aren't 'Page with redirect'",
  "# 3) Known SPA routes → /index.html (200)",
  "# Unknown paths fall through to Netlify 404.html (real HTTP 404).",
  "# Do NOT add /* /index.html 200 — that caused soft-404 / empty-shell indexing noise.",
  "",
];

for (const [from, to] of LEGACY_REDIRECTS) {
  redirectLines.push(`${from}    ${to}    301`);
  redirectLines.push(`${from}/   ${to}    301`);
}

redirectLines.push("");
redirectLines.push("# Trailing slash normalization");
for (const route of SPA_ROUTES) {
  redirectLines.push(`${route}/    ${route}    301`);
}
redirectLines.push("/team/*/    /team/:splat    301");

redirectLines.push("");
redirectLines.push("# SPA route rewrites (HTTP 200)");
for (const route of SPA_ROUTES) {
  redirectLines.push(`${route}    /index.html    200`);
}
redirectLines.push("/team/*    /index.html    200");
redirectLines.push("");

writeFileSync(join(publicDir, "_redirects"), redirectLines.join("\n"), "utf8");
console.log(`Wrote public/_redirects (${SPA_ROUTES.length} SPA routes)`);

// ─── sitemap.xml ────────────────────────────────────────────────────────────
const seen = new Set();
const urlEntries = [];

for (const { path, priority, changefreq } of SEO_PAGES) {
  const loc = toCanonical(path);
  if (seen.has(loc)) continue;
  seen.add(loc);
  urlEntries.push(`  <url>
    <loc>${loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`);
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
        xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9
        http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd">
${urlEntries.join("\n")}
</urlset>
`;

writeFileSync(join(publicDir, "sitemap.xml"), sitemap, "utf8");
console.log(`Wrote public/sitemap.xml (${seen.size} URLs, host ${SITE_URL})`);

// ─── sitemap-images.xml ────────────────────────────────────────────────────
const imageEntries = IMAGE_SITEMAP.map((entry) => {
  const images = entry.images
    .map(
      (image) => `    <image:image>
      <image:loc>${escapeXml(image.loc)}</image:loc>
      <image:title>${escapeXml(image.title)}</image:title>
    </image:image>`,
    )
    .join("\n");
  return `  <url>
    <loc>${toCanonical(entry.path)}</loc>
${images}
  </url>`;
}).join("\n");

writeFileSync(
  join(publicDir, "sitemap-images.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${imageEntries}
</urlset>
`,
  "utf8",
);

writeFileSync(
  join(publicDir, "sitemap-index.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <sitemap>
    <loc>${SITE_URL}/sitemap.xml</loc>
    <lastmod>${today}</lastmod>
  </sitemap>
  <sitemap>
    <loc>${SITE_URL}/sitemap-images.xml</loc>
    <lastmod>${today}</lastmod>
  </sitemap>
</sitemapindex>
`,
  "utf8",
);

writeFileSync(
  join(publicDir, "robots.txt"),
  `User-agent: *
Allow: /
Disallow: /style-guide
Disallow: /newsletter/unsubscribe
Disallow: /privacy-policy
Disallow: /terms-of-service

User-agent: OAI-SearchBot
Allow: /

User-agent: CCBot
Allow: /

User-agent: PerplexityBot
Allow: /

User-agent: ClaudeBot
Allow: /

Sitemap: ${SITE_URL}/sitemap-index.xml
`,
  "utf8",
);

console.log("Wrote image sitemap, sitemap index, and robots.txt");

function escapeXml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}
